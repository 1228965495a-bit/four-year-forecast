export function applyCSCopy(events: ScriptEvent[]) {
  return events.map((event) => {
    const routeWiredEvent =
      event.id === "computer_science_y2s2_transfer_011"
        ? {
            ...event,
            conditions: {
              all: [
                { type: "stat", key: "escapeImpulse", op: ">=", value: 30 },
                { type: "stat", key: "gpaWill", op: ">=", value: 48 },
              ],
            },
            options: (event.options ?? []).map((option) => ({
              ...option,
              ...(["a", "c"].includes(option.id)
                ? {
                    nextEventId: "computer_science_transfer_apply_001",
                    nextEvent: "computer_science_transfer_apply_001",
                  }
                : {}),
            })),
            choices: (event.choices ?? []).map((choice) => ({
              ...choice,
              ...(["a", "c"].includes(choice.id)
                ? {
                    nextEventId: "computer_science_transfer_apply_001",
                    nextEvent: "computer_science_transfer_apply_001",
                  }
                : {}),
            })),
          }
        : event;
    const eventCopy = CS_COPY[routeWiredEvent.id];
    if (!eventCopy) return routeWiredEvent;
    const sourceOptions = routeWiredEvent.options ?? routeWiredEvent.choices ?? [];
    const rewrittenOptions = sourceOptions.map((option, index) => ({
      ...option,
      text: eventCopy.options[index]?.[0] ?? option.text,
      feedback: eventCopy.options[index]?.[1] ?? option.feedback,
    }));
    return {
      ...routeWiredEvent,
      title: eventCopy.title,
      description: eventCopy.description,
      ...(routeWiredEvent.options ? { options: rewrittenOptions } : { choices: rewrittenOptions }),
    };
  });
}
