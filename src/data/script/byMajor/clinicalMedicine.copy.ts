export function applyClinicalMedicineCopy(events: any[]) {
  return events.map((event) => {
    const copy = COPY[event.id];
    if (!copy) return event;
    const sourceOptions = event.options ?? event.choices ?? [];
    const options = sourceOptions.map((option: any) => ({
      ...option,
      ...(copy.options?.[option.id] ?? {}),
    }));
    return {
      ...event,
      title: copy.title,
      description: copy.description,
      options,
      choices: options,
    };
  });
}
