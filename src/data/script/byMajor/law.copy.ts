export function applyLawCopy(events: any[]) {
  return events.map((event) => {
    const eventCopy = LAW_COPY[event.id];
    if (!eventCopy) return event;
    const sourceOptions = event.options ?? event.choices ?? [];
    const rewrittenOptions = sourceOptions.map((option: any, index: number) => ({
      ...option,
      text: eventCopy.options[index]?.[0] ?? option.text,
      feedback: eventCopy.options[index]?.[1] ?? option.feedback,
    }));
    return {
      ...event,
      title: eventCopy.title,
      description: eventCopy.description,
      ...(event.options ? { options: rewrittenOptions } : { choices: rewrittenOptions }),
    };
  });
}
